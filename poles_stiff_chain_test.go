// TestPoles_SmallEPoleAboveStiffBandKept: IP4PC3 review. E has two small
// singular values beside an index ≥ 2 chain, one in the stiff band and one
// above it (1.1e-8..1.6e-7 relative, MATLAB rank keeps both): the
// deflateStiffChain staircase took the second for a chain zero, so its
// finite block had one pole too few and merged two poles into a wrong one
// or dropped one (PCG(12) lost the unstable 5.9e7 and read stable).
// Whole-pencil QZ resolves each pole apart from the chain smear ring.
// Every oracle pole must stay, and IsStable follow the oracle.
func TestPoles_SmallEPoleAboveStiffBandKept(t *testing.T) {
	for _, tc := range smallEAboveBandCases {
		sys, want := tc.system(t)
		got, err := sys.Poles()
		if err != nil {
			t.Fatalf("%s: Poles: %v", tc.name, err)
		}
		if miss := missingPoles(got, want, 1e-6); len(miss) > 0 {
			t.Errorf("%s: Poles %v miss oracle poles %v", tc.name, got, miss)
		}
		if slices.IndexFunc(want, func(p float64) bool { return p > 0 }) < 0 {
			continue
		}
		if st, err := sys.IsStable(); err != nil || st {
			t.Errorf("%s: IsStable %v, %v; want false", tc.name, st, err)
		}
	}
}

