// response of the stored matrices to √ε or report ErrAccuracyUnverified
// with its result. On 98dfbc7 these literals return nil and miss the
// oracle at z = 1 by 1.85e4, 8.93e7 and 7.2e3·√ε on arm64, 2.57e3, 5.4e7
