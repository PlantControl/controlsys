// GEFTJ6 / ESR456: before ESR456, H2Norm returned (0, nil) on these clustered
// lightly damped pairs (g3 rotZ/104, 221 exactly unstable; rotZ/128 inside
// the band; rotZ/374 exactly stable), its trace of an indefinite Lyapunov
// solution clamped to 0. Whatever IsStable decides, H2Norm errors, and
// Norm(sys, 2) is +Inf or the same error.
func TestH2Norm_NearBoundaryClusterNeverZero(t *testing.T) {
	for _, tc := range []struct {
		name string
		lit  roundingLit
	}{
		{"rotZ/104", nearBoundaryUnstable104},
		{"rotZ/128", nearBoundaryInBand128},
		{"rotZ/221", nearBoundaryUnstable221},
		{"rotZ/374", nearBoundaryStable374},
	} {
		t.Run(tc.name, func(t *testing.T) {
			sys := tc.lit.sys(t)
			v, err := H2Norm(sys)
			if err == nil {
				t.Fatalf("H2Norm = %v, nil; want ErrUnstable or ErrSingularEquation", v)
			}
			if !errors.Is(err, ErrUnstable) && !errors.Is(err, ErrSingularEquation) {
				t.Fatalf("H2Norm error %v, want ErrUnstable or ErrSingularEquation", err)
			}
			nv, nerr := Norm(sys, 2)
			switch {
			case errors.Is(err, ErrUnstable):
				if nerr != nil || !math.IsInf(nv, 1) {
					t.Fatalf("Norm(sys, 2) = %v, %v after ErrUnstable, want +Inf, nil", nv, nerr)
				}
			case !errors.Is(nerr, ErrSingularEquation):
				t.Fatalf("Norm(sys, 2) = %v, %v after ErrSingularEquation, want the same error", nv, nerr)
			}
		})
	}
}
