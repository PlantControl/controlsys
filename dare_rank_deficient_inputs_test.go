// dareDescriptorGainBig returns the stabilizing solution X of the Dare of
// (A, B, Q, R) with E (nil for I), Y = EᵀXE and the gain K in 320 bits:
// with Ā = E⁻¹A and B̄ = E⁻¹B rounded to float64, Y solves the Dare of
// (Ā, B̄, Q, R) (dareDoublingBig) and K = (R + B̄ᵀYB̄)⁻¹B̄ᵀYĀ.
func dareDescriptorGainBig(A, B, Q, R, E *mat.Dense) (X, Y, K *mat.Dense) {
	n, m := B.Dims()
	if E != nil {
		A = hbDense(hbSolve(hbFrom(E), hbFrom(A)))
		B = hbDense(hbSolve(hbFrom(E), hbFrom(B)))
	}
	Y = dareDoublingBig(A, B, Q, R, nil)
	K = dareGainBig(A, B, R, mat.NewDense(n, m, nil), Y)
	if E == nil {
		return Y, Y, K
	}
	et := hbFrom(E).t()
	X = hbDense(hbSolve(et, hbSolve(et, hbFrom(Y)).t()).t())
	symmetrize(X.RawMatrix().Data, n, n)
	return X, Y, K
}

