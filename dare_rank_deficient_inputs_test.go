// Rank-deficient B without a cross term (m > n, duplicated or scaled
// duplicate inputs) under cheap control: R + BᵀXB loses R on B's null
// space, so the gain's null-space part, fixed by R alone since R > 0, came
// out O(1) wrong at Accuracy 0 with X and A − BK exact (XXC5C2: m > n,
// rel err 1.7 to 6.4; scaled duplicates 1.7e-3), or the solve failed with
// ErrNoStabilizing on a stable plant (duplicated inputs). Dare now takes
// the gain in the inputs of B's right singular vectors, where R₂₂ stays on
// the diagonal, and solves the problem of rank(B) inputs where the given
// one fails. The 320-bit doubling oracle and its gain move by 5e-16 to
// 2e-15 under eps perturbations keeping the column structure.
func TestDare_RankDeficientInputsWithoutCrossTermMatchGain(t *testing.T) {
	cases := []struct {
		name       string
		n, m       int
		a, b, q, r []float64
	}{
		{"m > n", 4, 6, dareWideInputA, dareWideInputB, dareWideInputQ, dareWideInputR},
		{"duplicated", 3, 2,
			[]float64{-0.3452900867058655, 0.256888472101785, 0.035599318863172164, -0.06670012452957441, 0.3200097907703936, -0.29464827716072034, -0.6679636000641717, -0.1688516650647648, 0.04443311731532673},
			[]float64{0.7731891517405639, 0.7731891517405639, -0.06753522398834019, -0.06753522398834019, -0.616505842061077, -0.616505842061077},
			[]float64{6.4480223269015375e+13, 4.3289015953178022e+12, 7.987832121698743e+12, 4.3289015953178022e+12, 3.884486230557119e+13, 6.351416393333523e+12, 7.987832121698743e+12, 6.351416393333523e+12, 3.2762838869485605e+12},
			[]float64{1.0390195762046885e-06, -1.6350173287201112e-08, -1.6350173287201112e-08, 1.0086030575455537e-06}},
		{"scaled duplicates", 3, 3,
			[]float64{0.42599978422853385, -0.08355622055502465, -0.14640248625596444, 0.25717707334343815, -0.167587412716095, 0.1036944454955766, 0.17891666964153785, -0.2714825483988226, 0.03676738585962084},
			[]float64{-0.4130429005494335, -0.20652145027471674, 0.826085801098867, 1.5508855126338683, 0.7754427563169342, -3.1017710252677366, -0.13632336387316135, -0.06816168193658068, 0.2726467277463227},
			[]float64{3.1668620217022116, -2.339232066007749, 0.6872827118611121, -2.339232066007749, 2.821148282463094, -1.7097750912335214, 0.6872827118611121, -1.7097750912335214, 2.090790452159725},
			[]float64{1.0147303646964118e-12, -1.7206111291104192e-14, 9.960630128633317e-15, -1.7206111291104192e-14, 1.0314982059645736e-12, 1.0676801666533172e-14, 9.960630128633317e-15, 1.0676801666533172e-14, 1.0768842778483472e-12}},
	}
	for _, c := range cases {
		A, B := mat.NewDense(c.n, c.n, c.a), mat.NewDense(c.n, c.m, c.b)
		Q, R := mat.NewDense(c.n, c.n, c.q), mat.NewDense(c.m, c.m, c.r)
		want := dareDoublingBig(A, B, Q, R, nil)
		wantK := dareGainBig(A, B, R, mat.NewDense(c.n, c.m, nil), want)
		for _, ns := range []bool{false, true} {
			for _, solve := range []struct {
				name string
				f    func(A, B, Q, R *mat.Dense, opts *RiccatiOpts) (*RiccatiResult, error)
			}{{"Dare", Dare}, {"Dlqr", Dlqr}} {
				name := fmt.Sprintf("%s %s NoScaling=%v", solve.name, c.name, ns)
				res, err := solve.f(A, B, Q, R, &RiccatiOpts{NoScaling: ns})
				if err != nil {
					t.Errorf("%s: %v", name, err)
					continue
				}
				if rel := relErr(res.X, want); res.Accuracy != 0 || !(rel <= 1e-10) {
					t.Errorf("%s: Accuracy %d, ‖X − X*‖/‖X*‖ = %.3g", name, res.Accuracy, rel)
				}
				if rel := relErr(res.K, wantK); !(rel <= 1e-8) {
					t.Errorf("%s: ‖K − K*‖/‖K*‖ = %.3g", name, rel)
				}
				for _, e := range res.Eig {
					if !(cmplx.Abs(e) < 1) {
						t.Errorf("%s: Eig %v not stable", name, e)
					}
				}
				if r := closedLoopRadiusBig(t, A, B, res.K); !(r < 1) {
					t.Errorf("%s: ρ(A − BK) = %g", name, r)
				}
			}
		}
	}
}

