// TestMinimalRealizationClusteredNearUnitKeepsOrder checks the 5Z5U2F rows:
// minimal models clustered near z = 1 that the staircase once cut below n
// with an O(1) response error. MATLAB minreal keeps a minimal system whole;
// a cut is accepted only within √ε of the 320-bit response. The rv4 gen50
// seed 315 literal comes from the original generator (same seed, dt and
// mechanism as the task's zzD2CMatched 315; identity unconfirmed).
func TestMinimalRealizationClusteredNearUnitKeepsOrder(t *testing.T) {
	cases := append(clusteredNearUnitModels(t), struct {
		name string
		sys  *System
	}{"rv4 gen50 315", underResolvedCluster315(t)})
	for _, tc := range cases {
		n, _, _ := tc.sys.Dims()
		res, err := tc.sys.MinimalRealization()
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		if res.Order != n {
			t.Errorf("%s: order %d, want %d", tc.name, res.Order, n)
		}
		if e := clusteredOracleMisfit(t, tc.sys, res.Sys); !(e <= math.Sqrt(eps())) {
			t.Errorf("%s: response misfit %.3g", tc.name, e)
		}
	}
}
