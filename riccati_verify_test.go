// TestRiccatiResidualTerms_ConditionFinite: residualTerms scored any X
// with an ill-conditioned R + BᵀXB as Inf because mat.Solve reports
// mat.Condition with a usable result. With X = 0 the discrete residual is
// Q itself.
func TestRiccatiResidualTerms_ConditionFinite(t *testing.T) {
	A := mat.NewDense(2, 2, []float64{0.5, 1, 0, 0.3})
	B := mat.NewDense(2, 2, []float64{1, 0, 0, 1})
	Q := mat.NewDense(2, 2, []float64{2, 1, 1, 3})
	R := mat.NewDense(2, 2, []float64{1, 0, 0, 1e-17})
	problem, err := newRiccatiProblem(A, B, Q, R, &RiccatiOpts{NoScaling: true})
	if err != nil {
		t.Fatal(err)
	}
	res, scale := problem.residualTerms(false, make([]float64, 4))
	if want := mat.Norm(Q, 2); !(math.Abs(res-want) <= 1e-15*want) || !(math.Abs(scale-want) <= 1e-15*want) {
		t.Errorf("residual %g, scale %g; want both %g", res, scale, want)
	}
}
