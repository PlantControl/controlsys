// TestDareReducedInputsRowsReturnValue pins cheap-control Dares with
// reduced inputs, S and an upper-triangular E (rv48 sweep seed 1676 and
// rv49v seeds 3775, 4739; GYQVD2) that returned ErrNotConverged after the
// gonum v0.20.12 bump while a 320-bit oracle certifies a stabilizing
// solution. Dare must return a value, with or without scaling, X within
// newtonTol and K within max(gainFloor, 4·kBand) of the 320-bit
// solution, kBand the move of the 320-bit K under eps perturbations of
// the data (sweep), and E⁻¹(A − BK) stable, at either Accuracy.
func TestDareReducedInputsRowsReturnValue(t *testing.T) {
	cases := []struct {
		name             string
		kBand            float64
		A, B, Q, R, S, E *mat.Dense
	}{
		{
			name: "rv48 1676", kBand: 1.24e-5,
			A: mat.NewDense(2, 2, []float64{0.5561197456339678, -0.15378737846060336, -0.16436750614003615, -0.024682211701084037}),
			B: mat.NewDense(2, 5, []float64{0.38033762261640636, 0.5891130340133576, -0.09377911980354647, 2.5558364313931925, 1.4568859603240722, -0.28866277612480723, -1.0187794683389684, 0.36862037453340313, -0.3233056009853006, 2.655491509937177}),
			Q: mat.NewDense(2, 2, []float64{1.907074899460168e+11, -2.9609639328397144e+11, -2.9609639328397144e+11, 4.597253843600676e+11}),
			R: mat.NewDense(5, 5, []float64{7.163679390184327e-09, 3.532666765028939e-10, 1.3335504456594452e-10, -1.9738198171586303e-10, -5.513264449923645e-11, 3.532666765028939e-10, 7.558627940285399e-09, 2.1499666590007985e-10, -3.9417598975764285e-10, 4.249437134320053e-11, 1.3335504456594452e-10, 2.1499666590007985e-10, 7.1488671973345055e-09, 5.115865143120892e-12, 5.629357466492653e-11, -1.9738198171586303e-10, -3.9417598975764285e-10, 5.115865143120892e-12, 7.300364814153682e-09, -9.831142072984307e-13, -5.513264449923645e-11, 4.249437134320053e-11, 5.629357466492653e-11, -9.831142072984307e-13, 7.168519820939519e-09}),
			S: mat.NewDense(2, 5, []float64{-0.04003900641729683, -0.03768578944404571, 0.04061451577236974, -0.014011000825019219, -0.07441009008813389, 0.062165389488327207, 0.05851173614418473, -0.06305893721624554, 0.02175376966977688, 0.11553064489112909}),
			E: mat.NewDense(2, 2, []float64{1.0182414405931177, -0.010989402943873683, 0, 2.7252380040259193e-07}),
		},
		{
			name: "rv49 3775", kBand: 7.44e-5,
			A: mat.NewDense(2, 2, []float64{0.7480988094706716, -0.06386642921882958, -0.08911262758837663, -0.5198801014011759}),
			B: mat.NewDense(2, 3, []float64{0.29162907798416127, -2.4467709863893266, 0.7718286222402931, -0.4768751207339166, -0.25237531328659724, 0.27755809067471415}),
			Q: mat.NewDense(2, 2, []float64{1.026287373206906e+09, 7.374796824249886e+09, 7.374796824249886e+09, 5.2994540923774284e+10}),
			R: mat.NewDense(3, 3, []float64{5.676362030442225e-13, -1.3749111302514902e-14, 8.999817535901797e-16, -1.3749111302514902e-14, 5.650769756627489e-13, -1.7526072538834441e-15, 8.999817535901797e-16, -1.7526072538834441e-15, 5.447023285780747e-13}),
			S: mat.NewDense(2, 3, []float64{8.89463546062847e-07, -3.5856657319116083e-06, -9.351465277063327e-07, 6.391594699536332e-06, -2.576622975482344e-05, -6.719867965623493e-06}),
			E: mat.NewDense(2, 2, []float64{1.0424282267548104, -0.3025400514682271, 0, 0.00013874453786245198}),
		},
		{
			name: "rv49 4739", kBand: 0.198,
			A: mat.NewDense(3, 3, []float64{0.516414266213106, -0.03022439522538093, 0.8977607857892121, 1.007581563970195, -0.3373489090612796, 0.38830079270442, 0.17098935679422872, 0.09502061498653191, 0.59204062745949}),
			B: mat.NewDense(3, 4, []float64{0.9297820824796021, -0.013201986434828228, 1.599402196839169, 0.23244552061990054, 0.8920180488638066, -0.36597625578040316, 0.5363476079288887, 0.22300451221595166, -0.27228933915144915, -0.38759098646352247, -0.9696488966513317, -0.06807233478786229}),
			Q: mat.NewDense(3, 3, []float64{1.8850481832165333e+10, -1.5826879346384573e+08, -1.4671643017479645e+10, -1.5826879346384573e+08, 1.3288260325398855e+06, 1.2318322996638367e+08, -1.4671643017479645e+10, 1.2318322996638367e+08, 1.1419183379443243e+10}),
			R: mat.NewDense(4, 4, []float64{3.692783679829032e-12, -3.823289172787455e-14, -1.2326173848438776e-13, 1.559579570836417e-13, -3.823289172787455e-14, 3.5112917407413564e-12, 4.956072619454363e-14, 2.292417109430712e-14, -1.2326173848438776e-13, 4.956072619454363e-14, 3.6291926140645492e-12, -9.913151461225938e-16, 1.559579570836417e-13, 2.292417109430712e-14, -9.913151461225938e-16, 3.812635188104905e-12}),
			S: mat.NewDense(3, 4, []float64{3.727979719150401e-05, 3.121884308466647e-05, 9.045638434121202e-05, -0.00010058956759733079, -3.1300146991513005e-07, -2.621136516476896e-07, -7.594725131299745e-07, 8.445507993071155e-07, -2.9015485175795043e-05, -2.429814395382624e-05, -7.040370593825562e-05, 7.829053072544987e-05}),
			E: mat.NewDense(3, 3, []float64{1.0655807040930523, 0.3319145304146136, 0.11109098316961068, 0, 1.0263504308871247, 0.2374523185283896, 0, 0, 8.506902538868659e-05}),
		},
	}
	for _, c := range cases {
		ref := riccatiExactReference(false, c.A, c.B, c.Q, c.R, c.S, c.E, riccatiExactPrec)
		if !ref.OK {
			t.Fatalf("%s: 320-bit oracle did not certify", c.name)
		}
		for _, ns := range []bool{false, true} {
			res, err := acceptUnverified(Dare(c.A, c.B, c.Q, c.R, &RiccatiOpts{S: c.S, E: c.E, NoScaling: ns}))
			if err != nil {
				t.Errorf("%s NoScaling %v: %v", c.name, ns, err)
				continue
			}
			eX, eK := relErr(res.X, ref.X), relErr(res.K, ref.K)
			t.Logf("%s NoScaling %v: Accuracy %d, X err %.3g, K err %.3g", c.name, ns, res.accuracy, eX, eK)
			if eX > newtonTol || eK > max(gainFloor, 4*c.kBand) {
				t.Errorf("%s NoScaling %v: Accuracy %d with X off by %.3g, K by %.3g", c.name, ns, res.accuracy, eX, eK)
			}
			if dareRotatedInputsUnstable(c.A, c.B, c.E, res.K) {
				t.Errorf("%s NoScaling %v: E⁻¹(A − BK) unstable in %d bits", c.name, ns, riccatiExactPrec)
			}
		}
	}
}
