// GEFTJ6 / ESR456: clustered lightly damped pairs within rounding of the
// stability boundary (g3 rotZ/104, exactly unstable; rotZ/128, 451, 880,
// strictly stable inside the band). Before ESR456, Gram returned nil
// indefinite Gramians here. Whatever IsStable decides, Gram errors.
func TestGram_NearBoundaryClusterNeverNil(t *testing.T) {
	for _, tc := range []struct {
		name string
		lit  roundingLit
	}{
		{"rotZ/104", nearBoundaryUnstable104},
		{"rotZ/128", nearBoundaryInBand128},
		{"rotZ/451", nearBoundaryInBand451},
		{"rotZ/880", nearBoundaryInBand880},
	} {
		t.Run(tc.name, func(t *testing.T) {
			sys := tc.lit.sys(t)
			for _, typ := range []GramType{GramControllability, GramObservability} {
				g, err := Gram(sys, typ)
				if err == nil {
					t.Fatalf("Gram(%v) = %v, nil; want ErrUnstableGramian or ErrSingularEquation", typ, mat.Formatted(g))
				}
				if !errors.Is(err, ErrUnstableGramian) && !errors.Is(err, ErrSingularEquation) {
					t.Fatalf("Gram(%v) error %v, want ErrUnstableGramian or ErrSingularEquation", typ, err)
				}
			}
		})
	}
}
