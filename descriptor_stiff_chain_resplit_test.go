// stiffChainCase is a descriptor A = U·F·V, E = U·W·V, B = U·b, C = c·V
// (Gaussian U, V; float64 products kept as literals) beside its structured
// oracle (F, W, b, c, D): F = blkdiag(f, I), W = blkdiag(w, N), N
// nilpotent Jordan chains, b driving each chain only at its kernel state
// (proper), the first finite pole small in E (w ~ 1e-9..1e-8) or large in
// A. All entries row-major.
type stiffChainCase struct {
	name       string
	n, m, p    int
	a, e, b, c []float64
	d          []float64
	f, w       []float64
	sb, sc     []float64
}

func (tc stiffChainCase) systems(t *testing.T) (sys, oracle *System) {
	t.Helper()
	n, m, p := tc.n, tc.m, tc.p
	var err error
	sys, err = NewDescriptor(mat.NewDense(n, n, tc.a), mat.NewDense(n, m, tc.b), mat.NewDense(p, n, tc.c), mat.NewDense(p, m, tc.d), mat.NewDense(n, n, tc.e), 0)
	if err != nil {
		t.Fatal(err)
	}
	oracle, err = NewDescriptor(mat.NewDense(n, n, tc.f), mat.NewDense(n, m, tc.sb), mat.NewDense(p, n, tc.sc), mat.NewDense(p, m, tc.d), mat.NewDense(n, n, tc.w), 0)
	if err != nil {
		t.Fatal(err)
	}
	return sys, oracle
}

var stiffChainPoints = []complex128{0.05i, 0.37i, complex(0.5, 3)}

// requireDataDetermined checks the oracle against the exact rational solve
// of C(sE − A)⁻¹B + D for the literal data at stiffChainPoints: the response
// there is a function of the stored data, not of the construction.
func requireDataDetermined(t *testing.T, tc stiffChainCase, oracle *System) {
	t.Helper()
	for _, s := range stiffChainPoints {
		x, ok := fzExactDescResponse(tc.n, tc.m, tc.p, tc.a, tc.e, tc.b, tc.c, tc.d, s)
		if !ok {
			t.Fatalf("%s: exact solve singular at %v", tc.name, s)
		}
		o := pencilResponse(t, oracle, s)
		if d := stiffChainRelDiff(o, func(i, j int) complex128 { return x[i*tc.m+j] }); d > 1e-9 {
			t.Fatalf("%s: exact solve misses the oracle by %.3g at %v", tc.name, d, s)
		}
	}
}

func stiffChainRelDiff(o [][]complex128, g func(i, j int) complex128) float64 {
	var diff, size float64
	for i := range o {
		for j := range o[i] {
			diff = max(diff, cmplx.Abs(g(i, j)-o[i][j]))
			size = max(size, cmplx.Abs(o[i][j]))
		}
	}
	return diff / size
}

// tfMisses returns the largest relative miss of the transfer function of
// sys against the oracle at stiffChainPoints.
func tfMisses(t *testing.T, tc stiffChainCase, sys, oracle *System) float64 {
	t.Helper()
	res, err := sys.TransferFunction(nil)
	if err != nil {
		t.Fatalf("%s: TransferFunction: %v", tc.name, err)
	}
	worst := 0.0
	for _, s := range stiffChainPoints {
		g, err := res.TF.Eval(s)
		if err != nil {
			t.Fatalf("%s: Eval(%v): %v", tc.name, s, err)
		}
		worst = max(worst, stiffChainRelDiff(pencilResponse(t, oracle, s), func(i, j int) complex128 { return g[i][j] }))
	}
	return worst
}

// TestTransferFunction_StiffChainQZCountResplit: KLVET5. A proper chain
// beside a finite pole small in E (E singular value 5e-9..6e-9 relative):
// QZ smears the chain to |λ| ~ ε^(−1/k) and keeps one finite eigenvalue too
// many (a chain member, the pole lost or paired), and its split refitted at
// low frequency gave IsProper true with a wrong transfer function (base:
// 1.88, 0.031 and 1.21 relative off the structured oracle at 0.05i..0.5+3i,
// natively). The staircase of deflateStiffChain counts the finite poles
// right and its split now carries the reduction.
func TestTransferFunction_StiffChainQZCountResplit(t *testing.T) {
	for _, tc := range stiffChainResplitCases {
		sys, oracle := tc.systems(t)
		requireDataDetermined(t, tc, oracle)
		pr, err := sys.IsProper()
		if err != nil || !pr {
			t.Fatalf("%s: IsProper %v, %v; want true", tc.name, pr, err)
		}
		if miss := tfMisses(t, tc, sys, oracle); miss > 1e-8 {
			t.Errorf("%s: transfer function %.3g relative off the oracle", tc.name, miss)
		}
		if _, err := Step(sys, 1); err != nil {
			t.Errorf("%s: Step: %v", tc.name, err)
		}
	}
}

// TestTransferFunction_StiffChainNoWrongProperValue: KLVET5. Proper chains
// beside a pole small in E whose QZ split base refitted to a wrong proper
// transfer function (0.661, 0.706 and 0.074 relative off, IsProper true);
// the staircase re-split of these does not reproduce under 4ε copies of
// the data near the stiff pole, and base itself fails closed on the
// copies. They must fail closed (ErrDescriptorSingular from IsProper, Step
// and TransferFunction alike) or match the oracle.
func TestTransferFunction_StiffChainNoWrongProperValue(t *testing.T) {
	for _, tc := range stiffChainClosedCases {
		sys, oracle := tc.systems(t)
		requireDataDetermined(t, tc, oracle)
		_, perr := sys.IsProper()
		_, serr := Step(sys, 1)
		_, terr := sys.TransferFunction(nil)
		if perr != nil || serr != nil || terr != nil {
			for _, e := range []error{perr, serr, terr} {
				if !errors.Is(e, ErrDescriptorSingular) {
					t.Errorf("%s: IsProper %v, Step %v, TF %v: want all ErrDescriptorSingular or values", tc.name, perr, serr, terr)
					break
				}
			}
			continue
		}
		if miss := tfMisses(t, tc, sys, oracle); miss > 1e-8 {
			t.Errorf("%s: transfer function %.3g relative off the oracle", tc.name, miss)
		}
	}
}

// TestIsProper_LargePoleChainAbsorbedLeakRefit: KLVET5. A proper MIMO
// chain beside a pole large in A: the split leaves s-terms that
// absorbStiffLeak explains as the pole's moved residue (more equations
// than unknowns), but the absorbed reduction keeps a second-order
// remainder above reductionMatchTol at the data scale, so base kept the
// s-terms and read the model improper (TF right within 1e-9). The
// absorbed reduction refitted to the pencil samples is proper and
// matches the oracle.
