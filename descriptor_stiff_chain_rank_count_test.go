// TestDeflateStiffChainNeverKeepsFullRank checks that a stiff-chain
// staircase of an index ≥ 2 pencil never reports all rank(E) values
// finite: the chains the generator built (want < rank(E)) and the index gate
// of deflateStiffChain both require more than n − rank(E) infinite
// eigenvalues. The rows above are undecided (ok false) on every platform.
func TestDeflateStiffChainNeverKeepsFullRank(t *testing.T) {
	for _, tc := range stiffChainFullRankRows {
		A, E := mat.NewDense(tc.n, tc.n, tc.a), mat.NewDense(tc.n, tc.n, tc.e)
		r := stiffChainERank(E)
		if tc.want >= r {
			t.Fatalf("%s: structural count %d not below rank(E) %d", tc.name, tc.want, r)
		}
		if _, index1 := pencilIndexOne(A, E, tc.n, mat.Norm(A, 2)); index1 {
			t.Fatalf("%s: pencil reported index 1", tc.name)
		}
		if _, _, _, _, nf, _, _, _, ok := deflateStiffChain(A, E); ok {
			t.Errorf("%s: deflateStiffChain nf %d ok, want undecided (rank(E) %d, structural %d)", tc.name, nf, r, tc.want)
		}
	}
	for _, set := range [][]stiffChainCase{stiffChainResplitCases, stiffChainClosedCases, largePoleAbsorbCases} {
		for _, tc := range set {
			A, E := mat.NewDense(tc.n, tc.n, tc.a), mat.NewDense(tc.n, tc.n, tc.e)
			if _, _, _, _, nf, _, _, _, ok := deflateStiffChain(A, E); ok && nf >= stiffChainERank(E) {
				t.Errorf("%s: deflateStiffChain nf %d, rank(E) %d", tc.name, nf, stiffChainERank(E))
			}
		}
	}
}

// TestDescriptorStiffChainFullRankReductionFailsClosed checks the public
// side of the rows above: the Weierstrass reduction reports the chain left
// among the finite eigenvalues (errChainLeft) on every platform, not a
// split at rank(E) that its verification then rejects.
func TestDescriptorStiffChainFullRankReductionFailsClosed(t *testing.T) {
	for _, tc := range stiffChainFullRankRows {
		b, c := mat.NewDense(tc.n, 1, nil), mat.NewDense(1, tc.n, nil)
		for i := range tc.n {
			b.Set(i, 0, 1+0.1*float64(i))
			c.Set(0, i, 1-0.05*float64(i))
		}
		sys, err := NewDescriptor(mat.NewDense(tc.n, tc.n, tc.a), b, c, mat.NewDense(1, 1, []float64{0.1}), mat.NewDense(tc.n, tc.n, tc.e), 0)
		if err != nil {
			t.Fatal(err)
		}
		if _, _, err := sys.weierstrassReduceParts(); !errors.Is(err, errChainLeft) {
			t.Errorf("%s: reduction err %v, want %v", tc.name, err, errChainLeft)
		}
	}
}
