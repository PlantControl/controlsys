// checkDescriptorClosedLoop requires E⁻¹(A − BK) stable with eigenvalues
// res.Eig, each within 1e-6 of the largest or 1e4·eps·‖F‖·κ of an
// eigenvalue of F = E⁻¹(A − BK) of condition κ (F can be far from
// normal). It reports whether the closed loop is stable.
func checkDescriptorClosedLoop(t *testing.T, name string, continuous bool, A, B, E *mat.Dense, res *RiccatiResult) bool {
	t.Helper()
	var bk, acl, f mat.Dense
	bk.Mul(B, res.K)
	acl.Sub(A, &bk)
	if err := f.Solve(E, &acl); err != nil {
		t.Fatal(err)
	}
	var eg mat.Eigen
	if !eg.Factorize(&f, mat.EigenBoth) {
		t.Fatalf("%s: eig failed", name)
	}
	vals := eg.Values(nil)
	var right, left mat.CDense
	eg.VectorsTo(&right)
	eg.LeftVectorsTo(&left)
	n := len(vals)
	fn := mat.Norm(&f, 2)
	scale, stable := 0.0, true
	tol := make([]float64, n)
	for i, v := range vals {
		scale = max(scale, cmplx.Abs(v))
		if continuous && !(real(v) < 0) || !continuous && !(cmplx.Abs(v) < 1) {
			t.Errorf("%s: closed loop eigenvalue %v not stable", name, v)
			stable = false
		}
		var xn, yn float64
		var yx complex128
		for k := range n {
			x, y := right.At(k, i), left.At(k, i)
			xn += real(x)*real(x) + imag(x)*imag(x)
			yn += real(y)*real(y) + imag(y)*imag(y)
			yx += cmplx.Conj(y) * x
		}
		tol[i] = 1e4 * eps() * fn * math.Sqrt(xn*yn) / cmplx.Abs(yx)
	}
	for _, w := range res.Eig {
		d, at := math.Inf(1), 0
		for i, v := range vals {
			if dv := cmplx.Abs(v - w); dv < d {
				d, at = dv, i
			}
		}
		if !(d <= max(1e-6*scale, tol[at])) {
			t.Errorf("%s: Eig %v is %.3g from eig(E⁻¹(A − BK)) %v (tol %.3g)", name, w, d, vals, tol[at])
		}
	}
	return stable
}
