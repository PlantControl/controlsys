type descriptorRiccatiCase struct {
	name       string
	continuous bool
	noScaling  bool
	// wantX requires a solution; otherwise an error is also accepted.
	wantX            bool
	n, m             int
	a, b, q, r, e, s []float64
}

func descriptorDiag(d ...float64) []float64 {
	n := len(d)
	e := make([]float64, n*n)
	for i, v := range d {
		e[i*n+i] = v
	}
	return e
}

// descriptorExplicitGain returns a stabilizing gain of the explicit model
// (E⁻¹A, E⁻¹B) to seed descriptorOracle, or nil.
func descriptorExplicitGain(t *testing.T, continuous bool, A, B, Q, R, S, E *mat.Dense) *mat.Dense {
	t.Helper()
	var ea, eb mat.Dense
	if err := ea.Solve(E, A); err != nil {
		t.Fatal(err)
	}
	if err := eb.Solve(E, B); err != nil {
		t.Fatal(err)
	}
	for _, o := range []*RiccatiOpts{{S: S, NoScaling: true}, {S: S}} {
		var res *RiccatiResult
		var err error
		if continuous {
			res, err = Care(&ea, &eb, Q, R, o)
		} else {
			res, err = Dare(&ea, &eb, Q, R, o)
		}
		if err == nil {
			return res.K
		}
	}
	return nil
}

