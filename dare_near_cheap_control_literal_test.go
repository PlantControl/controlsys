// TestDareStabilizableNearCheapControlLiteral pins a stabilizing value on
// a near-cheap-control Dare (R ~4e-13, Q ~5e8, m = 6 > n = 4, cross term
// S): rv49vGen(4080) with Q·(1 − 171·eps), arm64-generated literal. amd64
// once returned ErrNoStabilizing here though the 320-bit reference is a
// stabilizing solution (OBRHK3); main returns Accuracy 1 on amd64 (K
// 2.8e-3 off) and Accuracy 0 natively. Either way the value must be the
// stabilizing solution: X within newtonTol of the reference, a small
// 320-bit residual, and A − BK stable.
func TestDareStabilizableNearCheapControlLiteral(t *testing.T) {
	A := mat.NewDense(4, 4, []float64{-0.48859292037978136, 0.41793270390763165, -0.9603490020315995, -0.22567503393966012, -0.49394724609639656, -0.2621462812093623, 0.0028578169301681135, -0.30825247405510403, -0.20121223102671446, -0.5457848901690595, 0.23235530073430805, -0.43838580962365, 0.10004015314371112, 0.058709309642481174, 0.37737900137265595, 0.047339777061303503})
	B := mat.NewDense(4, 6, []float64{-1.0716695382647656, 0.1353684110757145, -0.29333101615075263, -0.19715674050641407, 0.3582602012273356, 0.8475973633852412, 0.6594210571897688, -0.35763229876248415, -0.792863878461425, 0.440946911457474, -1.1053337823826903, 2.5878169152572776, -0.7325091371080434, 0.8321426431705353, -0.15181644197749916, -0.7317210025032546, -1.4803032603860966, 0.11541567930085184, -0.3976298607983385, -1.2021307093985962, -0.9345547052082515, -1.2098069038666543, -0.4857609087991246, 0.43978155246176154})
	Q := mat.NewDense(4, 4, []float64{481478454.66552174, -241458554.32704163, 291935778.0635098, -59370896.9030803, -241458554.32704163, 833129041.6799308, -635514768.5975908, 320377175.01320976, 291935778.0635098, -635514768.5975908, 518107388.7107623, -214974583.7966776, -59370896.9030803, 320377175.01320976, -214974583.7966776, 209165198.43837798})
	R := mat.NewDense(6, 6, []float64{4.355686422252468e-13, -8.615712824067085e-15, -1.0037522942678948e-14, -4.1113449347696615e-15, 2.1718525002789293e-15, -3.5239853229391166e-15, -8.615712824067085e-15, 4.2212211363591727e-13, -2.5905224461312712e-15, 3.122924551824951e-15, -5.261992234366518e-15, 9.622031859430451e-15, -1.0037522942678948e-14, -2.5905224461312712e-15, 4.2141080594070935e-13, -4.710376579313612e-15, 3.1747193722376053e-15, -7.860215044882443e-15, -4.1113449347696615e-15, 3.122924551824951e-15, -4.710376579313612e-15, 4.19690653744506e-13, -5.193025370444712e-15, 1.200291322610194e-14, 2.1718525002789293e-15, -5.261992234366518e-15, 3.1747193722376053e-15, -5.193025370444712e-15, 4.148149386670308e-13, -7.634426073322754e-15, -3.5239853229391166e-15, 9.622031859430451e-15, -7.860215044882443e-15, 1.200291322610194e-14, -7.634426073322754e-15, 4.2788893507535344e-13})
	S := mat.NewDense(4, 6, []float64{-4.324039389408043e-05, 9.579653308005407e-06, 1.8451813252549992e-05, 3.4427836414795295e-05, 2.984998858584841e-05, 2.084715441600719e-05, 1.588768278451923e-05, -2.6197791933872307e-05, -1.3584523933184095e-05, 9.262461469256923e-06, -1.402675460632143e-05, -4.035561522244462e-05, -1.577096902444095e-05, 2.2556184844831155e-05, 1.2119646925648485e-05, -7.296881976983424e-07, 1.690217345703476e-05, 3.020913544743447e-05, 2.9034423352890742e-05, -1.6379662493719856e-06, -1.2282242309414668e-05, -7.055775858555275e-06, -5.510441150496821e-06, -2.6752138198401044e-05})
	ref := riccatiExactReference(false, A, B, Q, R, S, nil, riccatiExactPrec)
	if !ref.OK {
		t.Fatal("320-bit reference failed")
	}
	for _, ns := range []bool{false, true} {
		res, err := Dare(A, B, Q, R, &RiccatiOpts{S: S, NoScaling: ns})
		if errors.Is(err, ErrNoStabilizing) {
			t.Fatalf("NoScaling=%v: %v", ns, err)
		}
		if err != nil && !errors.Is(err, ErrAccuracyUnverified) {
			t.Fatalf("NoScaling=%v: %v", ns, err)
		}
		if d := relErr(res.X, ref.X); d > newtonTol {
			t.Errorf("NoScaling=%v: X %.3g off the 320-bit X", ns, d)
		}
		resid := riccatiResidualBig(false, A, B, Q, R, S, res.X)
		if r := mat.Norm(resid, 2) / (mat.Norm(res.X, 2) + mat.Norm(Q, 2)); r > newtonTol {
			t.Errorf("NoScaling=%v: relative residual %.3g", ns, r)
		}
		eig := make([]complex128, 4)
		if !closedLoopStable(A, B, res.K, nil, eig) {
			t.Errorf("NoScaling=%v: A − BK not stable", ns)
		}
		for _, v := range res.Eig {
			if !(cmplx.Abs(v) < 1) {
				t.Errorf("NoScaling=%v: Eig %v", ns, v)
			}
		}
	}
}
