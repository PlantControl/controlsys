// bandDescriptorCase is a frozen continuous descriptor with an LU
// condition estimate of E in [1e4, 1e6) (5ZCX6J census rows), with 320-bit
// references of the census Lsim input at dt 0.01 (lsimRef by sample index,
// lsimPeak the largest |y| over the 201 samples) and of the step response
// at t = 1 and 2. line is the rounding-aware bound max(1e-7, DC descriptor
// bar relative to |G(0)|) on the error relative to the peak.
type bandDescriptorCase struct {
	name          string
	a, b, c, d, e *mat.Dense
	lsimPeak      float64
	lsimRef       map[int]float64
	stepRef       [2]float64
	line          float64
}

func (k bandDescriptorCase) sys(t *testing.T) *System {
	t.Helper()
	sys, err := NewDescriptor(k.a, k.b, k.c, k.d, k.e, 0)
	if err != nil {
		t.Fatalf("%s: %v", k.name, err)
	}
	return sys
}

func bandLsimInput() ([]float64, *mat.Dense) {
	const nt, dt = 201, 0.01
	tt := make([]float64, nt)
	u := mat.NewDense(nt, 1, nil)
	for i := range nt {
		tt[i] = float64(i) * dt
		u.Set(i, 0, math.Sin(1.3*tt[i]/(dt*20))+0.5)
	}
	return tt, u
}

// checkBandResponses runs Lsim and Step (tFinal 1 and 2) on k, passes each
// result to accept, and checks every returned response against the
// references within k.line.
func checkBandResponses(t *testing.T, k bandDescriptorCase, accept func(api string, resp *TimeResponse, err error)) {
	t.Helper()
	sys := k.sys(t)
	tt, u := bandLsimInput()
	resp, err := Lsim(sys, u, tt, nil)
	accept("Lsim", resp, err)
	if resp != nil && k.lsimRef != nil {
		worst := 0.0
		for i, ref := range k.lsimRef {
			worst = math.Max(worst, math.Abs(resp.Y.At(0, i)-ref))
		}
		if !(worst <= k.line*k.lsimPeak) {
			t.Errorf("%s Lsim: max error %g over %g·%g", k.name, worst, k.line, k.lsimPeak)
		}
	}
	peak := math.Max(math.Abs(k.stepRef[0]), math.Abs(k.stepRef[1]))
	for j, tf := range []float64{1, 2} {
		resp, err := Step(sys, tf)
		accept("Step", resp, err)
		if resp == nil || k.lsimRef == nil {
			continue
		}
		last := len(resp.T) - 1
		if resp.T[last] != tf {
			t.Fatalf("%s Step: last sample at %g, want %g", k.name, resp.T[last], tf)
		}
		if e := math.Abs(resp.Y.At(0, last) - k.stepRef[j]); !(e <= k.line*peak) {
			t.Errorf("%s Step(%g): error %g over %g·%g", k.name, tf, e, k.line, peak)
		}
	}
}

// TestStepLsimBandRefusedSplitUnverified: a band descriptor whose pencil
// split is refused beside a stiff pair at 1e16–1e19, where the LU fold is
// O(1) wrong or overflows, never returns a response with a nil error: the
// fold's response comes with ErrAccuracyUnverified, or no response and
// ErrSchurFailed when a sample is not finite (5ZCX6J, Q2).
func TestStepLsimBandRefusedSplitUnverified(t *testing.T) {
	for _, k := range bandRefusedCases {
		checkBandResponses(t, k, func(api string, resp *TimeResponse, err error) {
			switch {
			case err == nil:
				t.Errorf("%s %s: nil error on a refused split", k.name, api)
			case resp != nil && !errors.Is(err, ErrAccuracyUnverified):
				t.Errorf("%s %s: response with err = %v, want ErrAccuracyUnverified", k.name, api, err)
			case resp != nil && !allFiniteDense(resp.Y):
				t.Errorf("%s %s: non-finite response returned", k.name, api)
			case resp == nil && !errors.Is(err, ErrSchurFailed):
				t.Errorf("%s %s: err = %v, want ErrSchurFailed", k.name, api, err)
			}
		})
	}
}

// TestStepLsimBandCertificateMarginAccuracy: band rows whose split
