// TestStepLsimFoldRouteUnchanged: below cond(E) 1e4, and for explicit
// models, the zero-state route keeps the LU fold, sample for sample.
func TestStepLsimFoldRouteUnchanged(t *testing.T) {
	desc := bandFoldCase.sys(t)
	fold, _, _, err := desc.timeResponseForm(nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, sys := range []*System{desc, fold} {
		if keep, parts, refused := sys.zeroStateRoute(); keep || parts != nil || refused != nil {
			t.Fatalf("zeroStateRoute = %t, %d parts, %v; want the fold", keep, len(parts), refused)
		}
	}
	same := func(api string, a, b *TimeResponse, ea, eb error) {
		t.Helper()
		if ea != nil || eb != nil {
			t.Fatalf("%s: errors %v, %v", api, ea, eb)
		}
		ra, ca := a.Y.Dims()
		if rb, cb := b.Y.Dims(); ra != rb || ca != cb {
			t.Fatalf("%s: dims %d×%d vs %d×%d", api, ra, ca, rb, cb)
		}
		for i := range ra {
			for j := range ca {
				if math.Float64bits(a.Y.At(i, j)) != math.Float64bits(b.Y.At(i, j)) {
					t.Fatalf("%s: sample (%d, %d) %v vs fold %v", api, i, j, a.Y.At(i, j), b.Y.At(i, j))
				}
			}
		}
	}
	tt, u := bandLsimInput()
	ra, ea := Lsim(desc, u, tt, nil)
	rb, eb := Lsim(fold, u, tt, nil)
	same("Lsim", ra, rb, ea, eb)
	ra, ea = Step(desc, 2)
	rb, eb = Step(fold, 2)
	same("Step", ra, rb, ea, eb)
}

// sameBandSamples fails unless a and b are both nil-error responses with
// bit-identical samples.
func sameBandSamples(t *testing.T, what string, a, b *TimeResponse, ea, eb error) {
	t.Helper()
	if ea != nil || eb != nil {
		t.Fatalf("%s: errors %v, %v", what, ea, eb)
	}
	ra, ca := a.Y.Dims()
	if rb, cb := b.Y.Dims(); ra != rb || ca != cb {
		t.Fatalf("%s: dims %d×%d vs %d×%d", what, ra, ca, rb, cb)
	}
	for i := range ra {
		for j := range ca {
			if math.Float64bits(a.Y.At(i, j)) != math.Float64bits(b.Y.At(i, j)) {
				t.Fatalf("%s: sample (%d, %d) %v vs fold %v", what, i, j, a.Y.At(i, j), b.Y.At(i, j))
			}
		}
	}
}

// TestLsimBandInitialStateFoldRoute: the band route is zero-state only
// (5ZCX6J): with x0 ≠ 0 a band descriptor, certified or refused, is
// simulated from its LU fold, forced and free response alike, sample for
// sample as Lsim of the fold from the scaled x0.
func TestLsimBandInitialStateFoldRoute(t *testing.T) {
	tt, u := bandLsimInput()
	for _, k := range []bandDescriptorCase{bandCertifiedCases[0], bandMarginCases[0]} {
		desc := k.sys(t)
		n, _, _ := desc.Dims()
		x0 := mat.NewVecDense(n, nil)
		for i := range n {
			x0.SetVec(i, 1-0.3*float64(i))
		}
		fold, fx0, _, err := desc.timeResponseForm(x0)
		if err != nil {
			t.Fatal(err)
		}
		ra, ea := Lsim(desc, u, tt, x0)
		rb, eb := Lsim(fold, u, tt, fx0)
		sameBandSamples(t, k.name+" Lsim x0", ra, rb, ea, eb)
	}
}

