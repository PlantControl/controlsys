// TestModelArrayStepBandUnverifiedStep: ModelArray.Step keeps a response
// that Step returns with ErrAccuracyUnverified (a refused band split,
// strad1m/47) beside a certified one, and comes with that error.
func TestModelArrayStepBandUnverifiedStep(t *testing.T) {
	models := []*System{bandRefusedCases[2].sys(t), bandCertifiedCases[0].sys(t)}
	arr, err := NewModelArray([]int{2}, models)
	if err != nil {
		t.Fatal(err)
	}
	single, serr := Step(models[0], 2)
	got, err := arr.Step(2)
	if single == nil {
		if got != nil || !errors.Is(err, ErrSchurFailed) {
			t.Fatalf("ModelArray.Step: response %t, err = %v; want ErrSchurFailed as Step (%v)", got != nil, err, serr)
		}
		return
	}
	if got == nil || !errors.Is(err, ErrAccuracyUnverified) {
		t.Fatalf("ModelArray.Step: response %t, err = %v; want the responses with ErrAccuracyUnverified", got != nil, err)
	}
	for i, m := range models {
		resp, rerr := got.ResponseFlat(i)
		want, _ := Step(m, 2)
		if rerr != nil || resp == nil {
			t.Fatalf("model %d: %v", i, rerr)
		}
		sameBandSamples(t, "ModelArray.Step", resp, want, nil, nil)
	}
}

// TestLsimBandZeroInitialStateZeroStateRoute: an explicit all-zero x0 is
// the zero-state response: the same route, error class and samples as a
// nil x0, on refused (strad1m/69, /4 on arm64) and certified band rows.
func TestLsimBandZeroInitialStateZeroStateRoute(t *testing.T) {
	tt, u := bandLsimInput()
	class := func(err error) string {
		switch {
		case err == nil:
			return "nil"
		case errors.Is(err, ErrAccuracyUnverified):
			return "unverified"
		case errors.Is(err, ErrSchurFailed):
			return "schur"
		}
		return err.Error()
	}
	for _, k := range []bandDescriptorCase{bandRefusedCases[0], bandMarginCases[0], bandCertifiedCases[0]} {
		sys := k.sys(t)
		n, _, _ := sys.Dims()
		ra, ea := Lsim(sys, u, tt, nil)
		rb, eb := Lsim(sys, u, tt, mat.NewVecDense(n, nil))
		if class(ea) != class(eb) {
			t.Fatalf("%s: nil x0 %v, zero x0 %v", k.name, ea, eb)
		}
		if (ra == nil) != (rb == nil) {
			t.Fatalf("%s: response nil %t vs %t", k.name, ra == nil, rb == nil)
		}
		if ra != nil {
			sameBandSamples(t, k.name+" Lsim zero x0", ra, rb, nil, nil)
		}
	}
}

