	B := mat.NewDense(7, 1, []float64{-0.814031892482405, -0.4646280257947994, -2.3195813070940106, 1.4421291233860218, 0.4557144823596554, -0.6802105241549241, -0.32564404085440896})
	C := mat.NewDense(1, 7, []float64{-3.755498109227659, -1.0649683718676173, 2.245513450282776, -1.1291533104108398, 3.0489310627612625, -1.6927842933861883, -1.5686041398619848})
