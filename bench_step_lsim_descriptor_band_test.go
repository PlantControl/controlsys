// benchDescriptorClass is a frozen 5ZCX6J census model of a cond(E)
// class: band (LU condition estimate of E in [1e4, 1e6)) strad1m rows whose
// pencil split certifies (certified, ζ″ 0.054) or is refused beside a
// near-defective stiff pair (refused; certified on amd64), a cond < 1e4 row
// (lo), a ≥ 1e6 row on the parts route (hi) and the explicit model of the
// lo row's A, B, C, D (explicit).
func benchDescriptorClass(b *testing.B, class string) *System {
	b.Helper()
	m, ok := benchClassMats[class]
	if !ok {
		b.Fatalf("class %q", class)
	}
	var sys *System
	var err error
	if class == "explicit" {
		sys, err = New(m[0], m[1], m[2], m[3], 0)
	} else {
		sys, err = NewDescriptor(m[0], m[1], m[2], m[3], m[4], 0)
	}
	if err != nil {
		b.Fatal(err)
	}
	return sys
}

func benchBandLsimInput() ([]float64, *mat.Dense) {
	const nt, dt = 201, 0.01
	tt := make([]float64, nt)
	u := mat.NewDense(nt, 1, nil)
	for i := range nt {
		tt[i] = float64(i) * dt
		u.Set(i, 0, 1)
	}
	return tt, u
}

var benchClasses = []string{"certified", "refused", "lo", "hi", "explicit"}

func BenchmarkStepDescriptorBand(b *testing.B) {
	for _, c := range benchClasses {
		b.Run(c, func(b *testing.B) {
			sys := benchDescriptorClass(b, c)
			b.ReportAllocs()
			for b.Loop() {
				_, _ = Step(sys, 2)
			}
		})
	}
}

func BenchmarkLsimDescriptorBand(b *testing.B) {
	tt, u := benchBandLsimInput()
	for _, c := range benchClasses {
		b.Run(c, func(b *testing.B) {
			sys := benchDescriptorClass(b, c)
			b.ReportAllocs()
			for b.Loop() {
				_, _ = Lsim(sys, u, tt, nil)
			}
		})
	}
}

func BenchmarkLsimInitialStateDescriptorBand(b *testing.B) {
	tt, u := benchBandLsimInput()
	for _, c := range []string{"certified", "refused"} {
		b.Run(c, func(b *testing.B) {
			sys := benchDescriptorClass(b, c)
			n, _, _ := sys.Dims()
			x0 := mat.NewVecDense(n, nil)
			for i := range n {
				x0.SetVec(i, 1)
			}
			b.ReportAllocs()
			for b.Loop() {
				_, _ = Lsim(sys, u, tt, x0)
			}
		})
	}
}

func BenchmarkC2DDescriptorBand(b *testing.B) {
	for _, c := range []string{"certified", "refused"} {
		b.Run(c, func(b *testing.B) {
			sys := benchDescriptorClass(b, c)
			b.ReportAllocs()
			for b.Loop() {
				_, _ = sys.C2D(0.01, C2DOptions{Method: C2DMethodZOH})
			}
		})
	}
}

