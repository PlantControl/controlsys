// The trim check of a MIMO row must sample that row's pole band: one row
// holds only fast poles, the other slow ones as well, so a band from the fast
// row accepts dropping all but the constant of the slow row's resolved
// numerator.
func TestTransferFunctionTrimGateMIMOPerRowBand(t *testing.T) {
	a := []float64{3812.7063642495305, -159520.86344021081, 16961.835234987226, 4991.643551329376, -99414.84496377705, 96338.06548387303, -46644.29912598755, 6195.396891041872, 11773.881177713562, 20436.8410069467, 44830.18391668644, 5611.483129610682, 28749.15700434836, -18364.954925082697, -13688.680912030928, 23045.735962189116, -14890.360475042962, 45015.335850997224, -59278.4126942957, -7533.210511932899, 17692.63156245044, -27258.96540299548, 42469.38993996133, -30569.521069062295, 5145.962853801846, -30964.627182244592, 1741.2051831628805, 322.2481391471443, -15894.311105292563, 16917.06153932903, 5151.731080833555, -12915.067670408855, -5061.446226272436, -5606.522587726196, -5089.578325510734, -692.115611591595, -11537.439300846887, 8331.479373017046, -11821.81401350526, 7650.525485589162, 5605.6482924269185, 38056.21004787052, 45727.034433702625, 6188.219056143884, 36512.46944614361, -27682.47865558073, -27161.20597795286, 41687.93515255189, -15835.47523477545, -64493.71272666847, -51735.12955140493, -4779.640782400274, -56409.686148354864, 42546.13311898774, 3484.1725876711716, -21464.616164695442, 3090.857021307144, -78404.26388335109, 23159.05324705615, 4148.891709001496, -49502.02226858588, 49625.29989850574, -39002.86434846224, 17939.845010681078}
	b := []float64{-12589.466294025304, -2686.728847641916, 15601.39236349537, -7503.951150224305, 1166.310234884208, 6520.043851260905, 7724.839987438285, -8032.634987332413}
	rows := [][]float64{
		{0.32020275647118773, 0.9602709776578228, 1.3823628406589958, 0.018684483972192162, 0.03084568936075227, 0.15561582713160832, -1.1729503230910288, 0.8471880242858507},
		{-15.363192569198825, -43.76804382064077, -32.92699642696105, 2.702145822430545, -45.17247593302971, 20.727980114771114, 17.18433453294004, -0.9670608808281513},
	}
	const n = 8
	var exact [2][2][]float64
	for r, c := range rows {
		en, ed := exactTFCoeffs(a, b, c, n)
		exact[r] = [2][]float64{en, ed}
	}
	for _, order := range [][]int{{0, 1}, {1, 0}} {
		c := append(append([]float64{}, rows[order[0]]...), rows[order[1]]...)
		sys, err := NewFromSlices(n, 1, 2, a, b, c, []float64{0, 0}, 0)
		if err != nil {
			t.Fatal(err)
		}
		res, err := sys.TransferFunction(nil)
		if err != nil {
			t.Fatal(err)
		}
		zpk, err := res.TF.ZPK()
		if err != nil {
			t.Fatal(err)
		}
		for i, r := range order {
			for _, w := range []float64{0.1, 1, 3, 10} {
				s := complex(0, w)
				ex := Poly(exact[r][0]).Eval(s) / Poly(exact[r][1]).Eval(s)
				g, _ := res.TF.Eval(s)
				z, _ := zpk.Eval(s)
				if e := cmplx.Abs(g[i][0]-ex) / cmplx.Abs(ex); e > 1e-4 {
					t.Errorf("order %v row %d w=%g: TF rel err %.3g, num %v", order, i, w, e, res.TF.Num[i][0])
				}
				if e := cmplx.Abs(z[i][0]-ex) / cmplx.Abs(ex); e > 1e-4 {
					t.Errorf("order %v row %d w=%g: ZPK rel err %.3g", order, i, w, e)
				}
			}
		}
	}
}
