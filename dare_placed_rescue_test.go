// Both scaling modes of the pencil left only an Accuracy 1 X (off by
// 2e-7 to 8e-4 against the 320-bit doubling oracle, on arm64 or amd64),
// while Hewer's iteration from a pole-placement gain certifies X to 1e-9:
// Q of rank below n with, in the last two, cheap control and a cross
// term. Draws 764, 1060 and 2531 of a rank-deficient-cost review sweep
// (TDHYKU follow-up).
func TestDare_PoorPencilSolutionIsCertifiedByPlacedHewer(t *testing.T) {
	cases := []struct {
		n, m          int
		a, b, q, r, s []float64
	}{
		{
			4, 3,
			[]float64{-5.601847152455967, 8.184469261554778, -5.638593924458118, 3.040868804067299, -1.3033770419590673, 6.02719857156096, 0.10386898519860285, -1.863247285562758, -0.5943315498472412, -8.528083233133412, -6.0767996303675735, -3.7242933048401667, -6.470769163695008, -11.247661533644836, -11.678900697253326, 15.189354193098197},
			[]float64{0.41421023132547935, -1.4914447918845042, -1.7490030612642586, -0.3474397085871817, -0.20033483348295938, 0.4809902731698732, -1.393584015008313, -1.3243414942803469, 0.11356186594063228, 0.2652866183059661, 1.4714125488339371, 1.067130424113477},
			[]float64{2.0834891212143716e+14, -1.639486772707256e+14, 2.0575415539060356e+14, 5.929178661245505e+13, -1.639486772707256e+14, 1.2901036297782003e+14, -1.6190687667033884e+14, -4.6656399062282125e+13, 2.0575415539060356e+14, -1.6190687667033884e+14, 2.0319171350328734e+14, 5.855337257021544e+13, 5.929178661245505e+13, -4.6656399062282125e+13, 5.855337257021544e+13, 1.6873214858198387e+13},
			[]float64{84.30371510681914, 25.826435855558206, -121.67637472658213, 25.826435855558206, 7.911927491828311, -37.27554735051405, -121.67637472658213, -37.27554735051405, 175.6167021555909},
			nil,
		},
		{
			2, 2,
			[]float64{17.485264997180696, 28.258890141893218, 17.771304382909577, 11.934819589210237},
			[]float64{-0.6714142063625134, 0.9561483400741891, 0.4256800967511194, 1.3292137865934084},
			[]float64{6.191247414743046e+14, -2.2688205520184975e+14, -2.2688205520184975e+14, 8.314231934914778e+13},
			[]float64{3.370697534203692e-12, 3.8499968348827805e-12, 3.8499968348827805e-12, 7.2523689398387275e-12},
			[]float64{-38.31132336500049, -62.21733121469952, 14.03941919984586, 22.79992226049826},
		},
		{
			2, 2,
			[]float64{-32.43873180276813, -84.85143267107476, -136.46187366799478, 171.22170131085994},
			[]float64{1.4408389646691444, 0.49076877023510046, -1.395082516181716, 0.740460553944832},
			[]float64{6.794259926411631e+13, 4.235440306090815e+13, 4.235440306090815e+13, 2.6403103179381992e+13},
			[]float64{1.388122503185529e-11, -1.2100882998921446e-12, -1.2100882998921446e-12, 1.113678139300774e-12},
			[]float64{-29.583507404806614, 2.779134445039115, -18.441917297095582, 1.7324709640275333},
		},
	}
	for i, c := range cases {
		A, B := mat.NewDense(c.n, c.n, c.a), mat.NewDense(c.n, c.m, c.b)
		Q, R := mat.NewDense(c.n, c.n, c.q), mat.NewDense(c.m, c.m, c.r)
		var S *mat.Dense
		if c.s != nil {
			S = mat.NewDense(c.n, c.m, c.s)
		}
		want := dareDoublingBig(A, B, Q, R, S)
		res, err := Dare(A, B, Q, R, &RiccatiOpts{S: S})
		if err != nil {
			t.Errorf("case %d: %v", i, err)
			continue
		}
		if rel := relErr(res.X, want); res.Accuracy != 0 || !(rel <= 1e-8) {
			t.Errorf("case %d: Accuracy %d, ‖X − X*‖/‖X*‖ = %.3g; want 0, ≤ 1e-8", i, res.Accuracy, rel)
		}
		if rel := relErr(hewerDareBig(A, B, Q, R, S, res.K, 30), want); !(rel <= 1e-12) {
			t.Errorf("case %d: Hewer from K reaches %.3g of X*", i, rel)
		}
	}
}
