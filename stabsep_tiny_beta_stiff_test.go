// Stabsep and Modsep keep the tiny-β stiff mode of a full-rank E, at the
// value Poles reports, in the part its pole selects, as amendment 3 of
// RL6IT7 does for β = 0: the parts' poles are those of the model and their
// sum is the pencil.
func TestStabsepModsepTinyBetaStiffModeKeptInItsPart(t *testing.T) {
	checked := 0
	for _, c := range stiffTinyBetaCases {
		sys := c.system(t)
		if !matlabRankFull(t, sys.E) {
			continue
		}
		want, err := sys.Poles()
		if err != nil || len(want) != c.n {
			t.Fatalf("%s: Poles = %v, %v", c.name, want, err)
		}
		stiff := largestPole(want)
		if cmplx.Abs(stiff) < 1e10 {
			t.Fatalf("%s: no stiff pole in %v", c.name, want)
		}
		checked++
		type split struct {
			name      string
			g1, g2    *System
			stiffInG1 bool
		}
		var splits []split
		if sep, err := Stabsep(sys); err != nil {
			t.Errorf("%s: Stabsep: %v", c.name, err)
		} else {
			splits = append(splits, split{"Stabsep", sep.Stable, sep.Unstable, real(stiff) < 0})
		}
		for _, cut := range []float64{0.5, 1e10} {
			if sep, err := Modsep(sys, cut); err != nil {
				t.Errorf("%s: Modsep(%g): %v", c.name, cut, err)
			} else {
				splits = append(splits, split{"Modsep", sep.Slow, sep.Fast, false})
			}
		}
		byMag := func(a, b complex128) int { return cmp.Compare(cmplx.Abs(a), cmplx.Abs(b)) }
		w := slices.Clone(want)
		slices.SortFunc(w, byMag)
		for _, s := range splits {
			p1, err1 := s.g1.Poles()
			p2, err2 := s.g2.Poles()
			if err1 != nil || err2 != nil {
				t.Errorf("%s %s: part Poles: %v, %v", c.name, s.name, err1, err2)
				continue
			}
			got := append(slices.Clone(p1), p2...)
			if len(got) != c.n {
				t.Errorf("%s %s: parts have poles %v + %v, want the %d of %v", c.name, s.name, p1, p2, c.n, want)
				continue
			}
			slices.SortFunc(got, byMag)
			for i := range w {
				if cmplx.Abs(got[i]-w[i]) > 1e-9*math.Max(1, cmplx.Abs(w[i])) {
					t.Errorf("%s %s: part poles %v, want %v", c.name, s.name, got, w)
					break
				}
			}
			in := p2
			if s.stiffInG1 {
				in = p1
			}
			if !slices.ContainsFunc(in, func(p complex128) bool { return cmplx.Abs(p-stiff) <= 1e-9*cmplx.Abs(stiff) }) {
				t.Errorf("%s %s: stiff pole %v not in its part (%v | %v)", c.name, s.name, stiff, p1, p2)
			}
			if rel := maxPencilRel(t, sys, []complex128{0.05i, 0.37i, complex(0.5, 3), 10i}, func(z complex128) [][]complex128 {
				g, q := pencilResponse(t, s.g1, z), pencilResponse(t, s.g2, z)
				for i := range g {
					for j := range g[i] {
						g[i][j] += q[i][j]
					}
				}
				return g
			}); rel > 1e-9 {
				t.Errorf("%s %s: parts off the pencil by %.3g", c.name, s.name, rel)
			}
		}
	}
	if checked == 0 {
		t.Skip("no model has full MATLAB rank E on this platform")
	}
}
